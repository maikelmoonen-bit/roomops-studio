using System.Reflection;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.Json.Serialization;
using RoomOps.Bridge;

namespace RoomOps.ContractGen;

public static class TypeScriptGenerator
{
    public static string Generate(BridgeRegistry registry) => new Emitter().Run(registry);

    private sealed class Emitter
    {
        private readonly Dictionary<Type, string> _names = [];
        private readonly Dictionary<string, Type> _byName = new(StringComparer.Ordinal);
        private readonly Queue<Type> _pending = new();
        private readonly SortedDictionary<string, string> _declarations = new(StringComparer.Ordinal);
        private readonly NullabilityInfoContext _nullability = new();

        public string Run(BridgeRegistry registry)
        {
            var methods = registry.Methods.Values.OrderBy(m => m.Name, StringComparer.Ordinal).ToList();
            var methodLines = methods.Select(m => $"  \"{m.Name}\": {{ kind: \"{m.Kind.ToString().ToLowerInvariant()}\"; request: {Ref(m.RequestType, null)}; response: {Ref(m.ResponseType, null)} }};").ToList();
            // Types that cross the bridge outside method signatures (error payloads).
            Ref(typeof(RoomOps.Domain.Common.DomainError), null);
            var eventLines = registry.Events.OrderBy(e => e.Topic, StringComparer.Ordinal).Select(e => $"  \"{e.Topic}\": {Ref(e.PayloadType, null)};").ToList();
            while (_pending.Count > 0) Declare(_pending.Dequeue());

            var sb = new StringBuilder();
            sb.Append("// <auto-generated>\n// Generated by tools/RoomOps.ContractGen from RoomOps.Bridge.BridgeContract. Do not edit by hand.\n// </auto-generated>\n/* eslint-disable */\n\n");
            foreach (var declaration in _declarations.Values) sb.Append(declaration).Append('\n');
            sb.Append("export interface BridgeMethods {\n").Append(string.Join("\n", methodLines)).Append("\n}\n\n");
            sb.Append("export interface BridgeEvents {\n").Append(string.Join("\n", eventLines)).Append("\n}\n\n");
            sb.Append("export type BridgeMethodName = keyof BridgeMethods;\nexport type BridgeEventTopic = keyof BridgeEvents;\n\n");
            sb.Append("export const BRIDGE_METHOD_NAMES = [\n").Append(string.Join("\n", methods.Select(m => $"  \"{m.Name}\","))).Append("\n] as const;\n");
            return sb.ToString();
        }

        private static string Camel(string name) => JsonNamingPolicy.CamelCase.ConvertName(name);

        private string Name(Type type)
        {
            if (_names.TryGetValue(type, out var existing)) return existing;
            var name = type.Name.Split('`')[0];
            if (_byName.TryGetValue(name, out var other) && other != type)
            {
                throw new InvalidOperationException($"Type name collision: {type.FullName} and {other.FullName}");
            }
            _byName[name] = type;
            _names[type] = name;
            _pending.Enqueue(type);
            return name;
        }

        private string Ref(Type type, NullabilityInfo? info)
        {
            if (type.IsGenericParameter) return type.Name;
            var nullable = info?.ReadState == NullabilityState.Nullable;
            var underlying = Nullable.GetUnderlyingType(type);
            if (underlying is not null)
            {
                return Union(Ref(underlying, null), "null");
            }
            var core = Core(type, info);
            return nullable ? Union(core, "null") : core;
        }

        private static string Union(string a, string b) => a.EndsWith(" | null", StringComparison.Ordinal) ? a : $"{a} | {b}";

        private string Core(Type type, NullabilityInfo? info)
        {
            if (type.IsGenericParameter) return type.Name;
            if (type == typeof(string) || type == typeof(char) || type == typeof(Guid) || type == typeof(DateTime) || type == typeof(DateTimeOffset)
                || type == typeof(TimeOnly) || type == typeof(DateOnly) || type == typeof(TimeSpan) || type == typeof(Uri)) return "string";
            if (type == typeof(bool)) return "boolean";
            if (type == typeof(int) || type == typeof(long) || type == typeof(double) || type == typeof(decimal) || type == typeof(float) || type == typeof(short) || type == typeof(uint)) return "number";
            if (type == typeof(object) || type == typeof(JsonElement) || typeof(JsonNode).IsAssignableFrom(type)) return "unknown";
            if (type.IsEnum)
            {
                return Name(type);
            }
            if (type.IsArray)
            {
                return Array(Ref(type.GetElementType()!, info?.ElementType));
            }
            if (type.IsGenericType)
            {
                var def = type.GetGenericTypeDefinition();
                var args = type.GetGenericArguments();
                if (def == typeof(IReadOnlyDictionary<,>) || def == typeof(Dictionary<,>) || def == typeof(IDictionary<,>))
                {
                    return $"Record<string, {Ref(args[1], info?.GenericTypeArguments.ElementAtOrDefault(1))}>";
                }
                if (def == typeof(IReadOnlyList<>) || def == typeof(List<>) || def == typeof(IEnumerable<>) || def == typeof(IReadOnlyCollection<>)
                    || def == typeof(IReadOnlySet<>) || def == typeof(HashSet<>) || def == typeof(IList<>) || def == typeof(ICollection<>))
                {
                    return Array(Ref(args[0], info?.GenericTypeArguments.ElementAtOrDefault(0)));
                }
                var name = Name(def);
                return $"{name}<{string.Join(", ", args.Select((a, i) => Ref(a, info?.GenericTypeArguments.ElementAtOrDefault(i))))}>";
            }
            return Name(type);
        }

        private static string Array(string element) => element.Contains(' ', StringComparison.Ordinal) ? $"({element})[]" : $"{element}[]";

        private void Declare(Type type)
        {
            var name = _names[type];
            var sb = new StringBuilder();
            if (type.IsEnum)
            {
                var values = Enum.GetNames(type);
                if (type.GetCustomAttribute<FlagsAttribute>() is not null)
                {
                    sb.Append($"/** Flags enum serialized as a comma-separated list, e.g. \"{string.Join(", ", values.Skip(1).Take(2))}\". Values: {string.Join(", ", values)}. */\n");
                    sb.Append($"export type {name} = string;\n");
                    sb.Append($"export const {name}Values = [{string.Join(", ", values.Select(v => $"\"{v}\""))}] as const;\n");
                }
                else
                {
                    sb.Append($"export type {name} = {string.Join(" | ", values.Select(v => $"\"{v}\""))};\n");
                    sb.Append($"export const {name}Values = [{string.Join(", ", values.Select(v => $"\"{v}\""))}] as const;\n");
                }
                _declarations[name] = sb.ToString();
                return;
            }

            var polymorphic = type.GetCustomAttribute<JsonPolymorphicAttribute>();
            if (polymorphic is not null)
            {
                var discriminator = polymorphic.TypeDiscriminatorPropertyName ?? "$type";
                var derived = type.GetCustomAttributes<JsonDerivedTypeAttribute>().ToList();
                foreach (var d in derived)
                {
                    var derivedName = Name(d.DerivedType);
                    _ = derivedName;
                }
                sb.Append($"export type {name} =\n");
                sb.Append(string.Join("\n", derived.Select(d => $"  | ({_names[d.DerivedType]} & {{ {discriminator}: \"{d.TypeDiscriminator}\" }})"))).Append(";\n");
                sb.Append($"export type {name}Kind = {string.Join(" | ", derived.Select(d => $"\"{d.TypeDiscriminator}\""))};\n");
                _declarations[name] = sb.ToString();
                return;
            }

            var generic = type.IsGenericTypeDefinition ? $"<{string.Join(", ", type.GetGenericArguments().Select(a => a.Name))}>" : string.Empty;
            var ctorDefaults = type.GetConstructors().OrderByDescending(c => c.GetParameters().Length).FirstOrDefault()?.GetParameters()
                .Where(p => p.HasDefaultValue).Select(p => p.Name!).ToHashSet(StringComparer.OrdinalIgnoreCase) ?? [];
            sb.Append($"export interface {name}{generic} {{\n");
            foreach (var prop in type.GetProperties(BindingFlags.Public | BindingFlags.Instance).Where(p => p.GetIndexParameters().Length == 0 && p.GetMethod is { IsPublic: true }))
            {
                if (prop.GetCustomAttribute<JsonIgnoreAttribute>() is { Condition: JsonIgnoreCondition.Always }) continue;
                var info = _nullability.Create(prop);
                var computed = prop.SetMethod is null;
                var optional = computed || ctorDefaults.Contains(prop.Name);
                sb.Append($"  {(computed ? "readonly " : string.Empty)}{Camel(prop.Name)}{(optional ? "?" : string.Empty)}: {Ref(prop.PropertyType, info)};\n");
            }
            sb.Append("}\n");
            _declarations[name] = sb.ToString();
        }
    }
}
