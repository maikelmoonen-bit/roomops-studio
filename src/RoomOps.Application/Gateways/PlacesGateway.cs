using System.Text.Json.Nodes;
using RoomOps.Application.Commands;
using RoomOps.Application.Sessions;
using RoomOps.Domain.Common;
using RoomOps.Domain.Places;

namespace RoomOps.Application.Gateways;

/// <summary>Typed reads against Microsoft Places (MicrosoftPlaces module, Get-PlaceV3 / Get-PlacesSettings).</summary>
public sealed class PlacesGateway(ISessionManager sessions)
{
    private Task<CommandResult> Run(PsCommand command, CancellationToken ct) => sessions.Runner(ServiceKind.Places).RunAsync(command, ct);

    public bool IsAvailable => sessions.Current.IsConnected(ServiceKind.Places);

    /// <summary>Loads buildings, floors, sections and rooms. Desks and workspaces are out of scope for this release.</summary>
    public async Task<IReadOnlyList<Place>> GetHierarchyAsync(CancellationToken ct)
    {
        var all = new List<Place>();
        foreach (var type in new[] { "Building", "Floor", "Section", "Room" })
        {
            var result = await Run(PsCommand.Create("Get-PlaceV3", ("Type", type)), ct);
            all.AddRange(result.Objects.Select(o => Map(o, type)).Where(p => p is not null)!);
        }
        return all;
    }

    public async Task<Place?> GetPlaceAsync(string identity, CancellationToken ct)
    {
        try
        {
            var result = await Run(PsCommand.Create("Get-PlaceV3", ("Identity", identity)), ct);
            return result.Objects.Count == 0 ? null : Map(result.Objects[0], null);
        }
        catch (CommandFailedException ex) when (ex.Kind == ErrorKind.NotFound)
        {
            return null;
        }
    }

    public async Task<PlacesDiscoverySettings> GetSettingsAsync(CancellationToken ct)
    {
        var result = await Run(PsCommand.Create("Get-PlacesSettings"), ct);
        var raw = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (var o in result.Objects)
        {
            // Get-PlacesSettings emits either one object with properties or Name/Value pairs depending on the collection.
            if (o.Str("Name") is { } name && o.ContainsKey("Value"))
            {
                raw[name] = o.Str("Value") ?? string.Empty;
                continue;
            }
            foreach (var (key, value) in o)
            {
                raw[key] = value?.ToJsonString().Trim('"') ?? string.Empty;
            }
        }
        return new PlacesDiscoverySettings(raw.GetValueOrDefault("PlacesFinderEnabled"), raw.GetValueOrDefault("EnableBuildings"), raw);
    }

    public static Place? Map(JsonObject o, string? requestedType)
    {
        var id = o.Str("PlaceId");
        var typeText = o.Str("Type") ?? requestedType;
        if (id is null || !Enum.TryParse<PlaceType>(typeText, true, out var type)) return null;
        var identity = o.Str("Identity");
        return new Place
        {
            PlaceId = id,
            Type = type,
            DisplayName = o.Str("DisplayName") ?? identity ?? id,
            ParentId = o.Str("ParentId"),
            EmailAddress = identity is not null && identity.Contains('@') ? identity : null,
            Label = o.Str("Label"),
            Capacity = o.Int("Capacity"),
            Tags = o.StrList("Tags"),
            IsWheelChairAccessible = o.Bool("IsWheelChairAccessible"),
            AudioDeviceName = o.Str("AudioDeviceName"),
            VideoDeviceName = o.Str("VideoDeviceName"),
            DisplayDeviceName = o.Str("DisplayDeviceName"),
            MtrEnabled = o.Bool("MTREnabled"),
            Street = o.Str("Street"),
            City = o.Str("City"),
            State = o.Str("State"),
            PostalCode = o.Str("PostalCode"),
            CountryOrRegion = o.Str("CountryOrRegion"),
            Phone = o.Str("Phone"),
            GeoCoordinates = o.Str("GeoCoordinates"),
            SortOrder = o.Int("SortOrder") ?? o.Int("Floor"),
            FloorLabel = o.Str("FloorLabel"),
            TimeZone = o.Str("TimeZone"),
            IsManaged = o.Bool("IsManaged"),
            IsAutoGenerated = o.Bool("IsAutoGenerated"),
        };
    }
}
