using RoomOps.Domain.Common;

namespace RoomOps.Domain.Places;

public enum PlaceType
{
    Building,
    Floor,
    Section,
    Room,
    Workspace,
    Desk,
}

/// <summary>A Microsoft Places directory object (Get-PlaceV3). Places is authoritative; it is a different object from the Exchange mailbox.</summary>
public sealed record Place
{
    public required string PlaceId { get; init; }
    public required PlaceType Type { get; init; }
    public required string DisplayName { get; init; }
    public string? ParentId { get; init; }
    /// <summary>For mailbox-backed places (rooms, workspaces): the SMTP address Places reports as Identity.</summary>
    public string? EmailAddress { get; init; }
    public string? Label { get; init; }
    public int? Capacity { get; init; }
    public IReadOnlyList<string> Tags { get; init; } = [];
    public bool? IsWheelChairAccessible { get; init; }
    public string? AudioDeviceName { get; init; }
    public string? VideoDeviceName { get; init; }
    public string? DisplayDeviceName { get; init; }
    public bool? MtrEnabled { get; init; }
    public string? Street { get; init; }
    public string? City { get; init; }
    public string? State { get; init; }
    public string? PostalCode { get; init; }
    public string? CountryOrRegion { get; init; }
    public string? Phone { get; init; }
    public string? GeoCoordinates { get; init; }
    public int? SortOrder { get; init; }
    public string? FloorLabel { get; init; }
    public string? TimeZone { get; init; }
    public bool? IsManaged { get; init; }
    public bool? IsAutoGenerated { get; init; }
}

/// <summary>Hierarchy rules from the Set-PlaceV3 and New-Place references (Microsoft Learn).</summary>
public static class PlaceHierarchy
{
    public static IReadOnlyList<PlaceType> AllowedParents(PlaceType child) => child switch
    {
        PlaceType.Building => [],
        PlaceType.Floor => [PlaceType.Building],
        PlaceType.Section => [PlaceType.Floor],
        PlaceType.Room => [PlaceType.Floor, PlaceType.Section],
        PlaceType.Workspace => [PlaceType.Section],
        PlaceType.Desk => [PlaceType.Section],
        _ => [],
    };

    public static bool CanParent(PlaceType child, PlaceType parent) => AllowedParents(child).Contains(parent);

    public static string Rule(PlaceType child) => child switch
    {
        PlaceType.Building => Text.L("Buildings are top-level and have no parent.", "Gebouwen zijn het hoogste niveau en hebben geen bovenliggende locatie."),
        PlaceType.Floor => Text.L("A floor must belong to a building.", "Een verdieping moet bij een gebouw horen."),
        PlaceType.Section => Text.L("A section must belong to a floor.", "Een sectie moet bij een verdieping horen."),
        PlaceType.Room => Text.L("A room must belong to a floor or a section.", "Een ruimte moet bij een verdieping of sectie horen."),
        PlaceType.Workspace => Text.L("A workspace must belong to a section.", "Een werkplek moet bij een sectie horen."),
        PlaceType.Desk => Text.L("A desk must belong to a section.", "Een bureau moet bij een sectie horen."),
        _ => string.Empty,
    };

    /// <summary>Walks parents to build a path such as "Eindhoven HQ / Floor 3 / North wing". Cycles are cut defensively.</summary>
    public static IReadOnlyList<Place> Ancestors(Place place, IReadOnlyDictionary<string, Place> byId)
    {
        var chain = new List<Place>();
        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var current = place.ParentId;
        while (current is not null && byId.TryGetValue(current, out var parent) && seen.Add(current))
        {
            chain.Insert(0, parent);
            current = parent.ParentId;
        }
        return chain;
    }

    /// <summary>Returns true if moving <paramref name="placeId"/> under <paramref name="newParentId"/> would create a cycle.</summary>
    public static bool WouldCreateCycle(string placeId, string newParentId, IReadOnlyDictionary<string, Place> byId)
    {
        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        string? current = newParentId;
        while (current is not null && seen.Add(current))
        {
            if (current.Equals(placeId, StringComparison.OrdinalIgnoreCase)) return true;
            current = byId.TryGetValue(current, out var p) ? p.ParentId : null;
        }
        return false;
    }

    /// <summary>Properties Set-PlaceV3 can't update on rooms synchronized from on-premises Exchange.</summary>
    public static IReadOnlySet<string> HybridRestrictedRoomProperties { get; } =
        new HashSet<string>(["City", "CountryOrRegion", "GeoCoordinates", "Phone", "PostalCode", "State", "Street"], StringComparer.OrdinalIgnoreCase);
}

/// <summary>Get-PlacesSettings values relevant to room discovery.</summary>
public sealed record PlacesDiscoverySettings(string? PlacesFinderEnabled, string? EnableBuildings, IReadOnlyDictionary<string, string> Raw);
